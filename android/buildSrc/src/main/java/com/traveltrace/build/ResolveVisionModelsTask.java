package com.traveltrace.build;

import groovy.json.JsonSlurper;
import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.RegularFileProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.OutputFile;
import org.gradle.api.tasks.TaskAction;

import java.io.BufferedReader;
import java.io.File;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.net.HttpURLConnection;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * A2 explicit resolve step. Queries the LIVE Vertex/OpenAI model lists, selects vision
 * models via {@link VisionModelResolver}, and writes the committed generated file. NOT
 * wired into ordinary builds — run on demand / in CI.
 *
 * Failure modes are deliberately distinct:
 *   - missing API key -> "API key missing" GradleException (config problem)
 *   - zero suitable   -> NoSuitableModelException surfaced as build failure (PRD §4.3)
 */
public abstract class ResolveVisionModelsTask extends DefaultTask {

    @Input
    public abstract Property<String> getVertexApiKey();

    @Input
    public abstract Property<String> getOpenAiApiKey();

    @Input
    public abstract Property<String> getRulesetVersion();

    @OutputFile
    public abstract RegularFileProperty getOutputFile();

    @TaskAction
    public void resolve() throws Exception {
        String vKey = getVertexApiKey().getOrElse("").trim();
        String oKey = getOpenAiApiKey().getOrElse("").trim();
        if (vKey.isEmpty()) {
            throw new GradleException("VERTEX_API_KEY missing in local.properties — cannot resolve vision models. "
                    + "(Missing-key error, distinct from 'no suitable model'.)");
        }
        if (oKey.isEmpty()) {
            throw new GradleException("OPENAI_API_KEY missing in local.properties — cannot resolve vision models. "
                    + "(Missing-key error, distinct from 'no suitable model'.)");
        }

        List<VertexModel> vertex = fetchVertex(vKey);
        List<OpenAiModel> openAi = fetchOpenAi(oKey);

        String geminiModel;
        String openAiModel;
        try {
            String[] r = VisionModelResolver.select(vertex, openAi);
            geminiModel = r[0];
            openAiModel = r[1];
        } catch (NoSuitableModelException e) {
            throw new GradleException("Vision model resolution FAILED: " + e.getMessage(), e);
        }

        String iso = OffsetDateTime.now(ZoneOffset.UTC).toString();
        String json = "{\n"
                + "  \"geminiModel\": \"" + geminiModel + "\",\n"
                + "  \"openAiModel\": \"" + openAiModel + "\",\n"
                + "  \"rulesetVersion\": \"" + getRulesetVersion().get() + "\",\n"
                + "  \"resolvedAtIso\": \"" + iso + "\",\n"
                + "  \"_note\": \"GENERATED by ./gradlew resolveVisionModels — do not hand-edit.\"\n"
                + "}\n";
        File out = getOutputFile().get().getAsFile();
        if (out.getParentFile() != null) {
            out.getParentFile().mkdirs();
        }
        Files.write(out.toPath(), json.getBytes(StandardCharsets.UTF_8));
        getLogger().lifecycle("Resolved vision models -> gemini=" + geminiModel + ", openai=" + openAiModel
                + " (rulesetVersion=" + getRulesetVersion().get() + ")");
    }

    private String httpGet(String urlStr, Map<String, String> headers) throws Exception {
        HttpURLConnection conn = (HttpURLConnection) new URL(urlStr).openConnection();
        try {
            conn.setRequestMethod("GET");
            conn.setConnectTimeout(30_000);
            conn.setReadTimeout(30_000);
            if (headers != null) {
                for (Map.Entry<String, String> e : headers.entrySet()) {
                    conn.setRequestProperty(e.getKey(), e.getValue());
                }
            }
            int code = conn.getResponseCode();
            if (code < 200 || code >= 300) {
                throw new GradleException("HTTP " + code + " from " + urlStr + ": " + readAll(conn.getErrorStream()));
            }
            return readAll(conn.getInputStream());
        } finally {
            conn.disconnect();
        }
    }

    private static String readAll(InputStream in) throws Exception {
        if (in == null) return "";
        StringBuilder sb = new StringBuilder();
        try (BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            String line;
            while ((line = r.readLine()) != null) {
                sb.append(line).append('\n');
            }
        }
        return sb.toString();
    }

    /**
     * Vertex Express Mode: the API key goes in the x-goog-api-key header, and the endpoint
     * is region-less / project-less. This is the SAME surface the app calls at runtime, so
     * a model that resolves here is a model that actually answers :generateContent.
     */
    @SuppressWarnings("unchecked")
    private List<VertexModel> fetchVertex(String key) throws Exception {
        Map<String, String> headers = new HashMap<>();
        headers.put("x-goog-api-key", key);
        String body = httpGet(
                "https://aiplatform.googleapis.com/v1/publishers/google/models?pageSize=1000",
                headers);
        Object root = new JsonSlurper().parseText(body);
        List<VertexModel> result = new ArrayList<>();
        Object modelsObj = ((Map<String, Object>) root).get("publisherModels");
        if (modelsObj instanceof List) {
            for (Object o : (List<Object>) modelsObj) {
                Map<String, Object> m = (Map<String, Object>) o;
                Object name = m.get("name");
                Object stage = m.get("launchStage");
                result.add(new VertexModel(
                        name == null ? "" : name.toString(),
                        stage == null ? null : stage.toString()));
            }
        }
        return result;
    }

    @SuppressWarnings("unchecked")
    private List<OpenAiModel> fetchOpenAi(String key) throws Exception {
        Map<String, String> headers = new HashMap<>();
        headers.put("Authorization", "Bearer " + key);
        String body = httpGet("https://api.openai.com/v1/models", headers);
        Object root = new JsonSlurper().parseText(body);
        List<OpenAiModel> result = new ArrayList<>();
        Object dataObj = ((Map<String, Object>) root).get("data");
        if (dataObj instanceof List) {
            for (Object o : (List<Object>) dataObj) {
                Map<String, Object> m = (Map<String, Object>) o;
                Object id = m.get("id");
                result.add(new OpenAiModel(id == null ? "" : id.toString()));
            }
        }
        return result;
    }
}
